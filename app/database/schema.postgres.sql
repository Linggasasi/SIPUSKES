CREATE TABLE IF NOT EXISTS facilities (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  address TEXT NOT NULL,
  phone TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('patient', 'doctor', 'admin', 'staff')),
  email TEXT UNIQUE,
  phone TEXT UNIQUE,
  credential_hash TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (email IS NOT NULL OR phone IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS patients (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
  member_number TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  birth_date DATE,
  gender TEXT CHECK (gender IN ('Perempuan', 'Laki-laki', 'Tidak diketahui')),
  blood_type TEXT CHECK (blood_type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-', 'Tidak tahu')),
  address TEXT,
  emergency_phone TEXT,
  service_scheme TEXT NOT NULL DEFAULT 'subsidi' CHECK (service_scheme IN ('subsidi', 'mandiri')),
  unique_key_hash TEXT UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS staff (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
  facility_id INTEGER NOT NULL REFERENCES facilities(id) ON DELETE RESTRICT,
  staff_code TEXT NOT NULL UNIQUE,
  display_name TEXT NOT NULL,
  profession TEXT NOT NULL,
  license_number TEXT UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS clinics (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  facility_id INTEGER NOT NULL REFERENCES facilities(id) ON DELETE RESTRICT,
  code TEXT NOT NULL,
  name TEXT NOT NULL,
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (facility_id, code),
  UNIQUE (facility_id, name)
);

CREATE TABLE IF NOT EXISTS clinic_providers (
  provider_id INTEGER NOT NULL REFERENCES staff(id) ON DELETE RESTRICT,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
  PRIMARY KEY (provider_id, clinic_id)
);

CREATE TABLE IF NOT EXISTS schedules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id INTEGER NOT NULL REFERENCES staff(id) ON DELETE RESTRICT,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
  service_date DATE NOT NULL,
  starts_at TIME NOT NULL,
  ends_at TIME NOT NULL,
  capacity INTEGER NOT NULL CHECK (capacity > 0),
  status TEXT NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'unavailable', 'closed')),
  CHECK (ends_at > starts_at),
  UNIQUE (provider_id, clinic_id, service_date, starts_at)
);

CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
  facility_id INTEGER NOT NULL REFERENCES facilities(id) ON DELETE RESTRICT,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
  provider_id INTEGER REFERENCES staff(id) ON DELETE RESTRICT,
  queue_date DATE NOT NULL,
  queue_number TEXT NOT NULL,
  arrival_time TIME NOT NULL,
  complaint TEXT,
  status TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'called', 'in_service', 'completed', 'cancelled', 'no_show')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (facility_id, clinic_id, queue_date, queue_number)
);

CREATE TABLE IF NOT EXISTS screenings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
  appointment_id INTEGER REFERENCES appointments(id) ON DELETE SET NULL,
  complaint TEXT NOT NULL,
  health_history TEXT,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS visits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
  facility_id INTEGER NOT NULL REFERENCES facilities(id) ON DELETE RESTRICT,
  clinic_id INTEGER NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
  provider_id INTEGER REFERENCES staff(id) ON DELETE RESTRICT,
  appointment_id INTEGER UNIQUE REFERENCES appointments(id) ON DELETE SET NULL,
  visited_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  diagnosis TEXT,
  clinical_notes TEXT,
  status TEXT NOT NULL DEFAULT 'completed' CHECK (status IN ('in_progress', 'completed', 'referred'))
);

CREATE TABLE IF NOT EXISTS vitals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id INTEGER NOT NULL REFERENCES visits(id) ON DELETE CASCADE,
  measured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  systolic INTEGER CHECK (systolic > 0),
  diastolic INTEGER CHECK (diastolic > 0),
  heart_rate INTEGER CHECK (heart_rate > 0),
  temperature_c NUMERIC(4, 1) CHECK (temperature_c > 0),
  weight_kg NUMERIC(5, 2) CHECK (weight_kg > 0),
  height_cm NUMERIC(5, 2) CHECK (height_cm > 0)
);

CREATE TABLE IF NOT EXISTS medicines (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  strength TEXT,
  dosage_form TEXT,
  unit TEXT NOT NULL DEFAULT 'unit',
  minimum_stock INTEGER NOT NULL DEFAULT 0 CHECK (minimum_stock >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS inventory_batches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  facility_id INTEGER NOT NULL REFERENCES facilities(id) ON DELETE RESTRICT,
  medicine_id INTEGER NOT NULL REFERENCES medicines(id) ON DELETE RESTRICT,
  batch_number TEXT NOT NULL,
  expires_on DATE,
  quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (facility_id, medicine_id, batch_number)
);

CREATE TABLE IF NOT EXISTS prescriptions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id INTEGER NOT NULL REFERENCES visits(id) ON DELETE RESTRICT,
  patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
  prescribed_by INTEGER REFERENCES staff(id) ON DELETE RESTRICT,
  issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'dispensed', 'cancelled'))
);

CREATE TABLE IF NOT EXISTS prescription_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prescription_id INTEGER NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
  medicine_id INTEGER NOT NULL REFERENCES medicines(id) ON DELETE RESTRICT,
  dosage TEXT NOT NULL,
  frequency TEXT NOT NULL,
  duration_days INTEGER CHECK (duration_days > 0),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  instructions TEXT
);

CREATE TABLE IF NOT EXISTS consultations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id INTEGER NOT NULL REFERENCES patients(id) ON DELETE RESTRICT,
  provider_id INTEGER REFERENCES staff(id) ON DELETE RESTRICT,
  appointment_id INTEGER REFERENCES appointments(id) ON DELETE SET NULL,
  room_code TEXT NOT NULL UNIQUE,
  complaint TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'in_progress', 'completed', 'cancelled')),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at TIMESTAMPTZ,
  ended_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS beds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  facility_id INTEGER NOT NULL REFERENCES facilities(id) ON DELETE RESTRICT,
  code TEXT NOT NULL,
  bed_type TEXT NOT NULL CHECK (bed_type IN ('inpatient', 'emergency', 'observation')),
  status TEXT NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'occupied', 'maintenance')),
  UNIQUE (facility_id, code)
);

CREATE TABLE IF NOT EXISTS audit_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  entity_type TEXT NOT NULL,
  entity_id TEXT,
  details_json JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_appointments_patient_date ON appointments(patient_id, queue_date);
CREATE INDEX IF NOT EXISTS idx_appointments_queue ON appointments(facility_id, clinic_id, queue_date, status);
CREATE INDEX IF NOT EXISTS idx_schedules_provider_date ON schedules(provider_id, service_date);
CREATE INDEX IF NOT EXISTS idx_visits_patient_date ON visits(patient_id, visited_at DESC);
CREATE INDEX IF NOT EXISTS idx_inventory_medicine ON inventory_batches(facility_id, medicine_id);
CREATE INDEX IF NOT EXISTS idx_consultations_status ON consultations(status, requested_at);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON audit_logs(entity_type, entity_id, created_at);